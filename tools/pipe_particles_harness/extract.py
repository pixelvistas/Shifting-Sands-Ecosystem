"""Copies VegetationField::stepFlow(), addSourceInflow() and addSeepage()
verbatim from src/Games/VegetationField.cpp into gen/stepflow.inc, so the
harness compiles the real hydrology code against stub.h."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "../../src/Games/VegetationField.cpp")).read()

def grab(sig):
    i = src.index(sig); j = src.index("\n{", i); depth = 0; k = j + 1
    while True:
        c = src[k]
        if c == "{": depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0: return src[i:k + 1]
        k += 1

os.makedirs(os.path.join(here, "gen"), exist_ok=True)
with open(os.path.join(here, "gen/stepflow.inc"), "w") as f:
    f.write("// Generated by extract.py from src/Games/VegetationField.cpp - do not edit.\n")
    for sig in ["void VegetationField::stepFlow(float waterLevelFrac)",
                "float VegetationField::addSourceInflow(",
                "float VegetationField::addSeepage("]:
        f.write(grab(sig) + "\n\n")

# The app's default values for the statics stepFlow() reads.
import re
names = ["FLOW_GRAVITY", "FLOW_DAMPING_PER_SEC", "FLOW_SUBSTEPS", "FLOW_TERRAIN_SMOOTHING_SEC", "SOURCE_EDGE",
         "SINK_EDGE", "SOURCE_SPAN", "INFLOW_MM_PER_SEC", "ENABLE_WATER_TABLE", "WATER_TABLE_MM", "SEEPAGE_MM_PER_SEC",
         "USE_FLAT_SEA", "MIN_VISIBLE_WATER_DEPTH_FRAC", "WATER_HYSTERESIS_FRAC"]
with open(os.path.join(here, "gen/defaults.inc"), "w") as f:
    f.write("// Generated by extract.py from src/Games/VegetationField.cpp - do not edit.\n")
    for n in names:
        m = re.search(r"^(float|int|bool) VegetationField::%s = [^;]+;" % n, src, re.M)
        if not m: sys.exit("default not found: " + n)
        f.write(m.group(0) + "\n")
