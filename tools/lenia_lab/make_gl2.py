#!/usr/bin/env python3
"""Writes bin/data/shaders/lenia/GL2/* from GL3/* (branch prototype/6-lenia).

The two variants differ only in the GLSL version line, the rectangle-
texture extension, in/varying, texture/texture2DRect and
outputColor/gl_FragColor, so GL2 is generated rather than kept by hand
(CLAUDE.md: keep the two variants in sync). Run after editing a GL3 file:

    python3 tools/lenia_lab/make_gl2.py          # writes GL2
    python3 tools/lenia_lab/make_gl2.py --check  # exits 1 if GL2 is stale
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(REPO, "bin", "data", "shaders", "lenia", "GL3")
DST = os.path.join(REPO, "bin", "data", "shaders", "lenia", "GL2")

VERT_GL2 = """// LeniaLab: pass-through vertex shader for every pass. texcoord is the
// pass's own texel coordinate (world cells or projector pixels). Keep in
// sync with ../GL3/lenia.vert (generated by tools/lenia_lab/make_gl2.py).
#version 120

varying vec2 coord;

void main()
{
	coord = gl_MultiTexCoord0.xy;
	gl_Position = gl_ModelViewProjectionMatrix * gl_Vertex;
}
"""


def convert_frag(src):
    out = src.replace("#version 150", "#version 120\n#extension GL_ARB_texture_rectangle : enable")
    out = out.replace("../GL2/", "../GL3/")
    out = re.sub(r"^in vec2 coord;", "varying vec2 coord;", out, flags=re.M)
    out = re.sub(r"^out vec4 outputColor;\n", "", out, flags=re.M)
    out = re.sub(r"\boutputColor\b", "gl_FragColor", out)
    out = re.sub(r"\btexture\(", "texture2DRect(", out)
    return out


def main():
    check = "--check" in sys.argv
    stale = []
    os.makedirs(DST, exist_ok=True)
    for name in sorted(os.listdir(SRC)):
        src = open(os.path.join(SRC, name)).read()
        out = VERT_GL2 if name.endswith(".vert") else convert_frag(src)
        path = os.path.join(DST, name)
        old = open(path).read() if os.path.exists(path) else None
        if old != out:
            stale.append(name)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(out)
    if check:
        print("GL2 stale:" if stale else "GL2 up to date", " ".join(stale))
        sys.exit(1 if stale else 0)
    print("wrote", ", ".join(stale) if stale else "nothing (up to date)")


if __name__ == "__main__":
    main()
