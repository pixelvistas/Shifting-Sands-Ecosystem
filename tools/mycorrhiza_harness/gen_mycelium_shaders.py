"""Writes the "Mycelium" style's shaders (GL2 #version 120 and GL3 #version 150)
from one source, so the two variants cannot drift apart.

Port of tools/mycelium_lookdev/index.html (fsCurlField, fsLic, fsFib, fsShade,
fsThread, fsBright, fsBlur, fsFinal) to the module's grid-space image: every
full-screen pass gets `px`, its own pixel coordinate (x right, y = grid row,
origin top-left, as the uploaded data), and samples rectangle textures at
uv x size, which matches the page's normalised uv. The page's y axis points
up; here y points down, so the light directions' y components are negated.

Usage: python3 gen_mycelium_shaders.py <repoRoot>
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "."
out_dir = os.path.join(root, "bin", "data", "shaders", "mycorrhiza")

HEADER = "// Prototype 2 (Mycorrhiza), style \"Mycelium\": %s\n// Generated by tools/mycorrhiza_harness/gen_mycelium_shaders.py (edit there; GL2 and GL3 stay in sync).\n// Port of tools/mycelium_lookdev/index.html (%s); tools/mycorrhiza_harness/main.cpp has the same formulas in C++.\n"

COMMON = """float hash12(vec2 p)
{
	vec3 p3 = fract(vec3(p.xyx) * 0.1031);
	p3 += dot(p3, p3.yzx + 33.33);
	return fract((p3.x + p3.y) * p3.z);
}

float vnoise(vec2 p)
{
	vec2 i = floor(p), f = p - i;
	vec2 u = f * f * (3.0 - 2.0 * f);
	float a = hash12(i), b = hash12(i + vec2(1.0, 0.0));
	float c = hash12(i + vec2(0.0, 1.0)), d = hash12(i + vec2(1.0, 1.0));
	return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);
}
"""

RAMP = """vec3 ramp(float m)
{
	m = clamp(m, 0.0, 1.0) * 3.0;
	if (m < 1.0) return mix(uC0, uC1, m);
	if (m < 2.0) return mix(uC1, uC2, m - 1.0);
	return mix(uC2, uC3, m - 2.0);
}
"""

