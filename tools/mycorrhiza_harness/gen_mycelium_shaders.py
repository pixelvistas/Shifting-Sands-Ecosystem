def frag(ver, name, desc, page, uniforms, body):
    head = HEADER % (desc, page)
    if ver == 3:
        pre = "#version 150\n\n" + uniforms + "\n"
        if name == "myc_thread":
            pre += "in float vSide;\nin float vS;\nin float vPhase;\nin float vBirth;\n"
        else:
            pre += "in vec2 px;\n"
        pre += "out vec4 outputColor;\n\n"
        b = body.replace("TEX2(", "texture(").replace("TEX(", "texture(").replace("OUT", "outputColor")
    else:
        pre = "#version 120\n#extension GL_ARB_texture_rectangle : enable\n\n" + uniforms + "\n"
        if name == "myc_thread":
            pre += "varying float vSide;\nvarying float vS;\nvarying float vPhase;\nvarying float vBirth;\n"
        else:
            pre += "varying vec2 px;\n"
        pre += "\n"
        b = body.replace("TEX2(", "texture2D(").replace("TEX(", "texture2DRect(").replace("OUT", "gl_FragColor")
    return head + pre + b


for ver, d in ((2, "GL2"), (3, "GL3")):
    os.makedirs(os.path.join(out_dir, d), exist_ok=True)
    for name, (desc, page, uniforms, body) in FRAGS.items():
        with open(os.path.join(out_dir, d, name + ".frag"), "w") as f:
            f.write(frag(ver, name, desc, page, uniforms, body))
    with open(os.path.join(out_dir, d, "myc_quad.vert"), "w") as f:
        f.write(HEADER % ("full-screen pass; px = this pass's pixel coordinate (texcoord)", "vs") + QUAD_VERT[ver])
    with open(os.path.join(out_dir, d, "myc_thread.vert"), "w") as f:
        f.write(HEADER % ("thread segments as quads", "vsThread") + THREAD_VERT[ver])
print("written to", out_dir)
